var _ resource.Resource = (*tncResource)(nil)

// NewTNC returns the truenas_installer_tnc resource.
func NewTNC(cfg *config.Config) resource.Resource {
	return &tncResource{config: cfg}
}

type tncResource struct {
	config *config.Config
}

func (r *tncResource) Metadata(_ context.Context, _ resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = "truenas_installer_tnc"
}

