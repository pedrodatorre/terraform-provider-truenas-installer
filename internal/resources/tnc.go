func (r *tncResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan tncModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	cl, err := client.New(r.config.Endpoint, r.config.Timeout)
	if err != nil {
		resp.Diagnostics.AddError("Invalid installer endpoint", err.Error())
		return
	}
	connectCtx, cancel := context.WithTimeout(ctx, r.config.Timeout)
	defer cancel()
	if err := cl.ConnectWithRetry(connectCtx, 5*time.Second); err != nil {
		resp.Diagnostics.AddError(
			"Cannot reach the TrueNAS installer",
			"The installer's JSON-RPC server was not reachable at "+r.config.Endpoint+".\n\n"+err.Error(),
		)
		return
	}
	defer cl.Close()

	config, err := cl.ConfigureTNC(ctx, client.TNCConfigRequest{
		Enabled:                 plan.Enabled.ValueBool(),
		AccountServiceBaseURL:   plan.AccountServiceBaseURL.ValueString(),
		LecaServiceBaseURL:      plan.LecaServiceBaseURL.ValueString(),
		HeartbeatServiceBaseURL: plan.HeartbeatServiceBaseURL.ValueString(),
		TNCBaseURL:              plan.TNCBaseURL.ValueString(),
	})
	if err != nil {
		resp.Diagnostics.AddError("configure_tnc failed", err.Error())
		return
	}

	plan = flattenTNC(plan, config)
	plan.ID = types.StringValue("tnc:" + r.config.Endpoint)

	if plan.Enabled.ValueBool() {
		uri, err := cl.TNCRegistrationURI(ctx)
		if err != nil {
			tflog.Warn(ctx, "tnc_registration_uri failed; the URI may not be available yet", map[string]any{"error": err.Error()})
		} else {
			plan.RegistrationURI = types.StringValue(uri)
		}
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *tncResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state tncModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	cl, err := client.New(r.config.Endpoint, r.config.Timeout)
	if err != nil {
		return
	}
	connectCtx, cancel := context.WithTimeout(ctx, 5*time.Second)
	defer cancel()
	if err := cl.Connect(connectCtx); err != nil {
		tflog.Debug(ctx, "installer not reachable; keeping state", map[string]any{"error": err.Error()})
		return
	}
	defer cl.Close()

	config, err := cl.TNCConfig(ctx)
	if err != nil {
		tflog.Debug(ctx, "cannot read tnc_config; keeping state", map[string]any{"error": err.Error()})
		return
	}

	state = flattenTNC(state, config)
	if state.InitializationInProgress.ValueBool() {
		if uri, err := cl.TNCRegistrationURI(ctx); err == nil {
			state.RegistrationURI = types.StringValue(uri)
		}
	}
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

func (r *tncResource) Update(_ context.Context, _ resource.UpdateRequest, resp *resource.UpdateResponse) {
	resp.Diagnostics.AddError(
		"Cannot update in place",
		"configure_tnc can only be called once per installer boot. Replace the resource instead.",
	)
}

func (r *tncResource) Delete(_ context.Context, _ resource.DeleteRequest, _ *resource.DeleteResponse) {
	// No-op: TrueNAS Connect configuration cannot be removed through the installer API.
}

type tncModel struct {
	ID                       types.String `tfsdk:"id"`
	Enabled                  types.Bool   `tfsdk:"enabled"`
	AccountServiceBaseURL    types.String `tfsdk:"account_service_base_url"`
	LecaServiceBaseURL       types.String `tfsdk:"leca_service_base_url"`
	HeartbeatServiceBaseURL  types.String `tfsdk:"heartbeat_service_base_url"`
	TNCBaseURL               types.String `tfsdk:"tnc_base_url"`
	ClaimToken               types.String `tfsdk:"claim_token"`
	ClaimTokenExpiration     types.Int64  `tfsdk:"claim_token_expiration"`
	SystemID                 types.String `tfsdk:"system_id"`
	TruenasVersion           types.String `tfsdk:"truenas_version"`
	InitializationInProgress types.Bool   `tfsdk:"initialization_in_progress"`
	InitializationCompleted  types.Bool   `tfsdk:"initialization_completed"`
	InitializationError      types.String `tfsdk:"initialization_error"`
	RegistrationURI          types.String `tfsdk:"registration_uri"`
}

func flattenTNC(plan tncModel, config client.TNCConfig) tncModel {
	plan.Enabled = types.BoolValue(config.Enabled)
	plan.AccountServiceBaseURL = stringOrNull(config.AccountServiceBaseURL)
	plan.LecaServiceBaseURL = stringOrNull(config.LecaServiceBaseURL)
	plan.HeartbeatServiceBaseURL = stringOrNull(config.HeartbeatServiceBaseURL)
	plan.TNCBaseURL = stringOrNull(config.TNCBaseURL)
	plan.ClaimToken = stringOrNull(config.ClaimToken)
	plan.SystemID = stringOrNull(config.SystemID)
	plan.TruenasVersion = stringOrNull(config.TruenasVersion)
	plan.InitializationInProgress = types.BoolValue(config.InitializationInProgress)
	plan.InitializationCompleted = types.BoolValue(config.InitializationCompleted)
	plan.InitializationError = stringOrNull(config.InitializationError)
	if config.ClaimTokenExpiration != nil {
		plan.ClaimTokenExpiration = types.Int64Value(*config.ClaimTokenExpiration)
	} else {
		plan.ClaimTokenExpiration = types.Int64Null()
	}
	return plan
}

func stringOrNull(value *string) types.String {
	if value == nil {
		return types.StringNull()
	}
	return types.StringValue(*value)
}
